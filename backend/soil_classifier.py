class SoilClassifierService:
    """Singleton service to hold the MobileNetV3-Small soil classification model."""

    def __init__(self):
        self.device = self._select_device()
        self.model: Optional[nn.Module] = None
        self.class_names: list[str] = []
        self.num_classes: int = 7
        self.transform: Optional[transforms.Compose] = None
        self.is_loaded: bool = False
        self._load_model()

    def _select_device(self) -> torch.device:
        """Select best available compute device: CUDA > MPS (Apple Silicon) > CPU."""
        if torch.cuda.is_available():
            dev = torch.device("cuda")
        elif hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
            dev = torch.device("mps")
        else:
            dev = torch.device("cpu")
        logger.info(f"SoilClassifierService compute device: {dev}")
        return dev

    def _load_model(self):
        """Load checkpoint and construct MobileNetV3-Small architecture once."""
        if not os.path.exists(MODEL_PATH):
            logger.error(f"Soil classification model not found at {MODEL_PATH}")
            return

        try:
            checkpoint = torch.load(MODEL_PATH, map_location=self.device, weights_only=False)
            self.class_names = checkpoint.get(
                "class_names",
                ["Alluvial_Soil", "Arid_Soil", "Black_Soil", "Laterite_Soil", "Mountain_Soil", "Red_Soil", "Yellow_Soil"],
            )
            self.num_classes = checkpoint.get("num_classes", len(self.class_names))
            mean = checkpoint.get("mean", [0.485, 0.456, 0.406])
            std = checkpoint.get("std", [0.229, 0.224, 0.225])

            # Reconstruct MobileNetV3-Small architecture
            model = mobilenet_v3_small(weights=None)
            in_features = model.classifier[3].in_features
            model.classifier[3] = nn.Linear(in_features, self.num_classes)

            # Load trained weights
            model.load_state_dict(checkpoint["model_state_dict"])
            model = model.to(self.device)
            model.eval()

            self.model = model

            # Define validation/testing preprocessing pipeline
            self.transform = transforms.Compose([
                transforms.Resize(256),
                transforms.CenterCrop(224),
                transforms.ToTensor(),
                transforms.Normalize(mean=mean, std=std),
            ])

            self.is_loaded = True
            logger.info(f"Loaded MobileNetV3-Small soil classification model with {self.num_classes} classes on {self.device}")
        except Exception as e:
            logger.error(f"Failed to load soil classification model: {e}", exc_info=True)
            self.is_loaded = False

    def validate_image_bytes(self, content: bytes, filename: str = "") -> Image.Image:
        """
        Validate image bytes for:
        1. Non-empty
        2. Size <= MAX_FILE_SIZE (10MB)
        3. Extension allowed
        4. Valid decodable image via PIL
        5. Minimum dimensions (width >= 10, height >= 10)
        """
        if not content or len(content) == 0:
            raise ValueError("Uploaded file is empty.")

        if len(content) > MAX_FILE_SIZE:
            raise ValueError(f"File size exceeds maximum allowed limit of {MAX_FILE_SIZE // (1024 * 1024)} MB.")

        if filename:
            ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
            if ext and ext not in ALLOWED_EXTENSIONS:
                raise ValueError(f"File extension '.{ext}' is not supported. Allowed formats: {', '.join(sorted(ALLOWED_EXTENSIONS))}.")

        try:
            image = Image.open(io.BytesIO(content))
            image.verify()  # verify integrity
            # Re-open because verify() closes/invalidates the stream
            image = Image.open(io.BytesIO(content))
        except (UnidentifiedImageError, Exception) as e:
            raise ValueError("The uploaded file is not a valid, non-corrupted image file.") from e

        if image.width < 10 or image.height < 10:
            raise ValueError(f"Image dimensions ({image.width}x{image.height}) are too small for soil analysis.")

        return image

    def classify_image(self, image: Image.Image) -> Dict[str, Any]:
        """
        Run inference on the preprocessed PIL Image.
        Returns:
            predicted_soil: raw class identifier
            predicted_soil_name: friendly English name
            confidence: percentage rounded to 2 decimals
            probabilities: dict of class_name -> percentage
            soil_info: agronomic metadata
            disclaimer: limitation notice
        """
        if not self.is_loaded or self.model is None or self.transform is None:
            raise RuntimeError("Soil classification model is not loaded or failed to initialize.")

        # Ensure RGB format
        rgb_image = image.convert("RGB")

        # Apply preprocessing
        tensor = self.transform(rgb_image).unsqueeze(0).to(self.device)

        with torch.no_grad():
            outputs = self.model(tensor)
            probs_tensor = torch.softmax(outputs, dim=1)[0]

        # Extract values to CPU
        probs = probs_tensor.cpu().numpy()
        pred_idx = int(probs.argmax())
        confidence = float(probs[pred_idx] * 100.0)
        pred_class = self.class_names[pred_idx]

        # Build probabilities dictionary mapped by class name
        prob_dict = {
            self.class_names[i]: round(float(probs[i] * 100.0), 2)
            for i in range(len(self.class_names))
        }

        # Sort probabilities descending
        sorted_probs = dict(sorted(prob_dict.items(), key=lambda item: item[1], reverse=True))

        info = SOIL_INFO.get(pred_class, {
            "name_en": pred_class.replace("_", " "),
            "name_gu": pred_class.replace("_", " "),
            "description": "Visual soil classification.",
            "typical_crops": "Common regional crops",
            "characteristics": "Standard soil profile",
        })

        return {
            "predicted_soil": pred_class,
            "predicted_soil_name": info["name_en"],
            "confidence": round(confidence, 2),
            "probabilities": sorted_probs,
            "soil_info": info,
            "disclaimer": DISCLAIMER_TEXT,
        }


# Global singleton instance
